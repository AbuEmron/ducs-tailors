# A second, thinner arch inside the field. The reference has it, and it is what
# turns an outline into a doorway: one line reads as a shape, two read as depth.
ARCH_KEYLINE = _mirror(8.0, [
    ((33.4, 10.4), (34.8, 12.2), (36.2, 14.2)),
    ((39.3, 18.2), (41.9, 21.4), (41.9, 26.1)),
    ((41.9, 30.5), (41.8, 34.4), (41.5, 38.2)),
    ((41.2, 42.9), (37.3, 47.4), (32.0, 50.1)),
])
KEYLINE_STROKE = 0.85


# ── Crescent and star ────────────────────────────────────────────────────────

def _crescent(cx, cy, R, d, r):
    """
    A crescent as two exact arcs, from the intersection of two circles.

    Not two circles resolved with an even-odd fill: that renders as a near-solid
    disc in some rasterisers, and where it does work the horns come out as blunt
    stubs. Two arcs are one path, are exact, and survive into a VectorDrawable.

    R  radius of the disc; r  radius of the bite; d  distance between centres.
    """
    a = (d * d - r * r + R * R) / (2 * d)
    h = math.sqrt(R * R - a * a)
    return (f"M{cx + a:.3f} {cy - h:.3f} "
            f"A{R} {R} 0 1 0 {cx + a:.3f} {cy + h:.3f} "
            f"A{r} {r} 0 0 1 {cx + a:.3f} {cy - h:.3f} Z")


def _star(cx, cy, R, points=5, ratio=0.44, phase=-math.pi / 2):
    """A five-pointed star, point-up, sitting off the crescent's upper horn."""
    pts = []
    for i in range(points * 2):
        rad = R if i % 2 == 0 else R * ratio
        a = phase + i * math.pi / points
        pts.append(f"{cx + rad * math.cos(a):.2f} {cy + rad * math.sin(a):.2f}")
    return "M" + " L".join(pts) + " Z"


CRESCENT = _crescent(cx=29.9, cy=20.6, R=4.9, d=2.9, r=4.1)
STAR = _star(cx=35.0, cy=17.4, R=2.2)


