# ── The small cut ────────────────────────────────────────────────────────────
#
# Below 32px the keyline is a fifth of a pixel, the star is three pixels of
# noise beside the moon, the curled leaf tips turn to mush, and the calligraphy
# -- which is the thing that most needs to be legible or absent -- becomes a
# grey smear. Detail you cannot resolve does not read as detail; it reads as
# dirt over the parts that were legible.
#
# So the small cut is the arch, a larger crescent and star that now have the
# whole field to themselves, and one uncurled sweep a side.

SMALL_ARCH_STROKE = 5.2
