# ── The ink box ──────────────────────────────────────────────────────────────
#
# Computed from the paths, not typed in. The band's stroke pushes past the
# silhouette by half its width on every side and the leaf tips run wider and
# lower than the arch does, so the mark does not fill its own 64-unit square --
# and an icon laid out on the square rather than on the ink puts the leaf tips
# into the launcher's corner radius.
#
# It is computed rather than measured-and-hardcoded because a hardcoded box is
# correct exactly until the next time somebody nudges a leaf.

def _bbox(d, pad=0.0):
    from svgpathtools import parse_path
    x0, x1, y0, y1 = parse_path(d).bbox()
    return (x0 - pad, y0 - pad, x1 + pad, y1 + pad)


def _union(boxes):
    return (min(b[0] for b in boxes), min(b[1] for b in boxes),
            max(b[2] for b in boxes), max(b[3] for b in boxes))


INK = _union([
    _bbox(ARCH, ARCH_STROKE / 2), _bbox(LEAF_L), _bbox(LEAF_R),
    _bbox(CRESCENT), _bbox(STAR),
])

# How much of Android's 108dp adaptive viewport the mark occupies.
#
# 0.50 rather than the 0.62 that looks right in a preview, because the launcher
# only guarantees the central **66dp circle** and crops the rest to whatever
# shape the OEM prefers. The mark is a tall arch with leaves at the foot, so its
# widest-from-centre points are the leaf tips, and at 0.62 they sit 40.6dp out --
# comfortably inside a square mask and clipped by a circular one.
#
# This lives here, next to the geometry it depends on, because `build.py` places
# the icon with it and `validate.py` checks the icon against it, and the two
# quietly disagreeing is exactly how an icon ships cropped.
ADAPTIVE_MARGIN = 0.50
SAFE_RADIUS_DP = 33.0

SMALL_INK = _union([
    _bbox(ARCH, SMALL_ARCH_STROKE / 2), _bbox(SMALL_LEAF_L), _bbox(SMALL_LEAF_R),
    _bbox(SMALL_CRESCENT), _bbox(SMALL_STAR),
])
